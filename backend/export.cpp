// New file added to connect the backend to the frontend.
// It only writes out data that main.cpp already computed (exams, rooms,
// faculty, the conflict graph, and the two schedules) as a plain JS file.
// No scheduling/graph algorithm is implemented or changed here.

#include "export.h"
#include <fstream>

namespace {

const char* slotLabel(int slot) {
    static const char* labels[MAX_SLOTS] = {
        "9-10 AM", "10-11 AM", "11 AM-12 PM",
        "12-1 PM", "2-3 PM", "3-4 PM"
    };
    if (slot < 0 || slot >= MAX_SLOTS) return "";
    return labels[slot];
}

// Looks up why two exams conflict, purely for a human-readable label in the
// frontend's conflict panel. Does not decide scheduling behaviour.
string conflictReason(const Exam& a, const Exam& b) {
    bool sameInvigilator = (a.invigilatorId == b.invigilatorId);
    bool sharedStudent = false;

    for (int i = 0; i < a.studentCount && !sharedStudent; i++) {
        for (int j = 0; j < b.studentCount; j++) {
            if (a.studentIds[i] == b.studentIds[j]) {
                sharedStudent = true;
                break;
            }
        }
    }

    if (sameInvigilator && sharedStudent) return "Same invigilator and shared student(s)";
    if (sameInvigilator) return "Same invigilator";
    if (sharedStudent) return "Shared student(s)";
    return "Conflict";
}

void writeSchedule(
    ofstream& out,
    const ScheduleEntry schedule[],
    int examCount,
    bool success,
    double timeMs
) {
    out << "    success: " << (success ? "true" : "false") << ",\n";
    out << "    executionTimeMs: " << timeMs << ",\n";
    out << "    schedule: [\n";

    for (int i = 0; i < examCount; i++) {
        out << "      { examIndex: " << schedule[i].examIndex
            << ", timeSlot: " << schedule[i].timeSlot
            << ", roomIndex: " << schedule[i].roomIndex
            << ", scheduled: " << (schedule[i].scheduled ? "true" : "false")
            << " }" << (i + 1 < examCount ? ",\n" : "\n");
    }

    out << "    ]\n";
}

} // namespace

string resolveBackendDataPath() {
    // If index.html is right here, we're running with cwd = project root.
    ifstream rootCheck("index.html");
    if (rootCheck.is_open()) {
        return "backend_data.js";
    }

    // Otherwise assume cwd = backend/, as the README's compile steps use.
    return "../backend_data.js";
}

void exportResultsToJS(
    const char* filePath,
    const Exam exams[],
    int examCount,
    const Faculty faculty[],
    int facultyCount,
    const Room rooms[],
    int roomCount,
    const int conflictGraph[][MAX_EXAMS],
    const ScheduleEntry greedySchedule[],
    bool greedySuccess,
    double greedyTimeMs,
    const ScheduleEntry prioritySchedule[],
    bool prioritySuccess,
    double priorityTimeMs
) {
    ofstream out(filePath);
    if (!out.is_open()) {
        cout << "\n[export] Could not open " << filePath << " for writing.\n";
        return;
    }

    out << "// AUTO-GENERATED by backend/export.cpp — do not edit by hand.\n";
    out << "// Produced each time backend/main.cpp runs. Loaded by index.html\n";
    out << "// before script.js so the frontend can show the real schedule.\n";
    out << "const backendData = {\n";

    out << "  slotLabels: [";
    for (int s = 0; s < MAX_SLOTS; s++) {
        out << "\"" << slotLabel(s) << "\"" << (s + 1 < MAX_SLOTS ? ", " : "");
    }
    out << "],\n";

    out << "  rooms: [\n";
    for (int i = 0; i < roomCount; i++) {
        out << "    { id: " << rooms[i].id
            << ", name: \"" << rooms[i].name << "\""
            << ", capacity: " << rooms[i].capacity << " }"
            << (i + 1 < roomCount ? ",\n" : "\n");
    }
    out << "  ],\n";

    out << "  faculty: [\n";
    for (int i = 0; i < facultyCount; i++) {
        out << "    { id: " << faculty[i].id
            << ", name: \"" << faculty[i].name << "\" }"
            << (i + 1 < facultyCount ? ",\n" : "\n");
    }
    out << "  ],\n";

    out << "  exams: [\n";
    for (int i = 0; i < examCount; i++) {
        out << "    { index: " << i
            << ", id: " << exams[i].id
            << ", courseCode: \"" << exams[i].courseCode << "\""
            << ", courseName: \"" << exams[i].courseName << "\""
            << ", invigilatorId: " << exams[i].invigilatorId
            << ", studentCount: " << exams[i].studentCount << " }"
            << (i + 1 < examCount ? ",\n" : "\n");
    }
    out << "  ],\n";

    out << "  conflicts: [\n";
    bool first = true;
    for (int i = 0; i < examCount; i++) {
        for (int j = i + 1; j < examCount; j++) {
            if (conflictGraph[i][j] == 1) {
                if (!first) out << ",\n";
                out << "    { examA: " << i << ", examB: " << j
                    << ", reason: \"" << conflictReason(exams[i], exams[j]) << "\" }";
                first = false;
            }
        }
    }
    out << (first ? "" : "\n");
    out << "  ],\n";

    out << "  greedy: {\n";
    writeSchedule(out, greedySchedule, examCount, greedySuccess, greedyTimeMs);
    out << "  },\n";

    out << "  priority: {\n";
    writeSchedule(out, prioritySchedule, examCount, prioritySuccess, priorityTimeMs);
    out << "  }\n";

    out << "};\n";

    out.close();

    cout << "\n[export] Wrote " << filePath << " for the frontend.\n";
}
